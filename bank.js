// Consolidate all additions into one subject entry with unique board/topic lists.
const _merged = new Map();
for (const item of module.exports) {
  if (!_merged.has(item.subject)) _merged.set(item.subject, { subject: item.subject, boards: [] });
  const target = _merged.get(item.subject);
  for (const board of item.boards || []) {
    let b = target.boards.find(x => x.board === board.board);
    if (!b) { b = { board: board.board, topics: [] }; target.boards.push(b); }
    for (const topic of board.topics || []) {
      if (!b.topics.some(x => x.name === topic.name)) b.topics.push(topic);
    }
  }
}
module.exports = [..._merged.values()];
